#!/usr/bin/env bash
# Quality gates of the heelonvault-core crate, without the private heelonvault-premium repository.
#
# The full workspace does not load without ../heelonvault-premium (heelonvault-app declares it as a
# path dependency). This script mirrors the repository layout the core tests rely on (root
# Cargo.lock, heelonvault-app sources and migrations) into a separate directory whose workspace
# only contains heelonvault-core, then runs fmt, clippy, clippy-secure and the tests there.
#
# Usage: scripts/check-core-standalone.sh [--semver]
#   --semver  also run cargo semver-checks (requires cargo-semver-checks installed)
# Env: HEELONVAULT_CORE_STANDALONE_DIR  work directory (default: ~/.cache/heelonvault/core-standalone)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
WORK_DIR="${HEELONVAULT_CORE_STANDALONE_DIR:-${XDG_CACHE_HOME:-$HOME/.cache}/heelonvault/core-standalone}"

RUN_SEMVER=false
for arg in "$@"; do
  case "$arg" in
    --semver) RUN_SEMVER=true ;;
    *)
      echo "[ERROR] Unknown argument: $arg"
      exit 1
      ;;
  esac
done

# Synced sources are replaced on every run; target/ is kept to reuse build artifacts.
mkdir -p "$WORK_DIR/crates"
rm -rf "$WORK_DIR/crates/heelonvault-core" "$WORK_DIR/crates/heelonvault-app" "$WORK_DIR/.cargo"
cp -a "$REPO_ROOT/crates/heelonvault-core" "$WORK_DIR/crates/"
mkdir -p "$WORK_DIR/crates/heelonvault-app"
cp -a "$REPO_ROOT/crates/heelonvault-app/src" "$REPO_ROOT/crates/heelonvault-app/migrations" \
  "$WORK_DIR/crates/heelonvault-app/"
cp -a "$REPO_ROOT/.cargo" "$WORK_DIR/"
cp "$REPO_ROOT/Cargo.lock" "$REPO_ROOT/rust-toolchain.toml" "$REPO_ROOT/clippy.toml" "$WORK_DIR/"
cat > "$WORK_DIR/Cargo.toml" <<'EOF'
# Generated by scripts/check-core-standalone.sh: heelonvault-core only, no Premium.
[workspace]
members = ["crates/heelonvault-core"]
resolver = "2"
EOF

cd "$WORK_DIR"
echo "[INFO] Standalone heelonvault-core checks in $WORK_DIR"

cargo fmt -p heelonvault-core -- --check
cargo clippy -p heelonvault-core --all-targets --all-features -- -D warnings
# Same lints as the `cargo clippy-secure` alias, which cannot take -p (it ends with `--`).
cargo clippy -p heelonvault-core --all-targets --all-features -- \
  -D clippy::unwrap_used -D clippy::expect_used -D clippy::disallowed_methods \
  -D clippy::panic -D clippy::todo -D clippy::unimplemented
cargo test -p heelonvault-core --all-features

if [[ "$RUN_SEMVER" == true ]]; then
  cargo semver-checks -p heelonvault-core
fi

echo "[OK] heelonvault-core quality gates passed"
